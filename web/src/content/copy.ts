type Vars = Record<string, string | number | null | undefined>;

/** Fill `{key}` placeholders. Unknown or nullish keys are left as-is so gaps are visible in dev. */
export function fmt(template: string, vars: Vars = {}): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => {
    const v = vars[k];
    return v === null || v === undefined ? m : String(v);
  });
}

/** Pick the singular or plural form, then fill it. `{count}` is always available. */
export function plural(count: number, forms: { readonly one: string; readonly other: string }, vars: Vars = {}): string {
  return fmt(count === 1 ? forms.one : forms.other, { count, ...vars });
}

/** 1 → "1st", 2 → "2nd", 11 → "11th". For single-answer positions (averages use "#2.4"). */
export function ordinal(n: number): string {
  const r100 = n % 100;
  const suffix = r100 >= 11 && r100 <= 13 ? 'th' : ({ 1: 'st', 2: 'nd', 3: 'rd' } as Record<number, string>)[n % 10] ?? 'th';
  return `${n}${suffix}`;
}

