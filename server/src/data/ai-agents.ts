const BY_ID = new Map(AI_AGENTS.map((a) => [a.id, a]));

export function agentById(id: string): AiAgent | undefined {
  return BY_ID.get(id);
}

const MATCHERS = AI_AGENTS.filter((a) => a.uaDetectable && a.pattern).map((agent) => ({
  agent,
  re: new RegExp(agent.pattern, 'i'),
}));
/** One combined test so ordinary browser UAs are rejected with a single regex run. */
const ANY_AGENT = new RegExp(MATCHERS.map((m) => `(?:${m.agent.pattern})`).join('|'), 'i');

const CACHE_LIMIT = 5000;
const cache = new Map<string, AiAgent | null>();

/**
 * Returns the catalog agent whose UA pattern matches, or null.
 * When several patterns match (e.g. a Google-CloudVertexBot UA that also says Googlebot),
 * the longest matched token wins, so specific agents beat generic ones; ties keep catalog order.
 */
export function matchAgent(userAgent: string): AiAgent | null {
  if (!userAgent) return null;
  const hit = cache.get(userAgent);
  if (hit !== undefined) return hit;

  let best: AiAgent | null = null;
  if (ANY_AGENT.test(userAgent)) {
    let bestLen = 0;
    for (const { agent, re } of MATCHERS) {
      const m = re.exec(userAgent);
      if (m && m[0].length > bestLen) {
        best = agent;
        bestLen = m[0].length;
      }
    }
  }

  if (cache.size >= CACHE_LIMIT) cache.clear();
  cache.set(userAgent, best);
  return best;
}
